// Writes src/lib/icons.ts: the Phosphor icons the app uses, in only the weights it uses.
// Each Phosphor component carries all six weights, which made icons a large share of the
// bundle. Run `node scripts/icons.mjs` after changing the list below.
import { readFileSync, writeFileSync } from 'node:fs';

// name in the app: [Phosphor component, extra weights besides regular]
const ICONS = {
  search: ['MagnifyingGlass'],
  undo: ['ArrowCounterClockwise'],
  redo: ['ArrowClockwise'],
  history: ['ClockCounterClockwise'],
  wand: ['MagicWand'],
  filter: ['Funnel'],
  grid: ['SquaresFour'],
  gridSmall: ['GridNine'],
  keyboard: ['Keyboard'],
  rules: ['ListChecks'],
  list: ['ListBullets'],
  library: ['Books'],
  inbox: ['Tray'],
  plus: ['Plus'],
  close: ['X'],
  check: ['Check'],
  done: ['CheckCircle', 'fill'],
  lock: ['Lock'],
  dots: ['DotsThree', 'bold'],
  download: ['DownloadSimple'],
  trophy: ['Trophy', 'fill'],
  edit: ['PencilSimple'],
  trash: ['Trash'],
  gear: ['Gear'],
  bell: ['Bell'],
  clock: ['Clock'],
  timer: ['Timer'],
  users: ['Users'],
  copy: ['Copy'],
  merge: ['ArrowsMerge'],
  palette: ['Palette'],
  save: ['FloppyDisk'],
  steam: ['GameController'],
  warning: ['Warning', 'fill'],
  caret: ['CaretDown'],
  heart: ['Heart'],
  family: ['UsersThree', 'bold'],
  feedback: ['ChatCircleText'],
};

const lib = new URL('../node_modules/phosphor-svelte/lib/', import.meta.url);
const out = {};
for (const [name, [component, ...extra]] of Object.entries(ICONS)) {
  const source = readFileSync(new URL(`${component}.svelte`, lib), 'utf8');
  const shapes = {};
  for (const weight of ['regular', ...extra]) {
    const m = source.match(new RegExp(`weight === "${weight}"\\}\\s*([\\s\\S]*?)\\s*\\{:else`));
    if (!m) throw new Error(`${component} has no ${weight} weight`);
    shapes[weight] = m[1].trim();
  }
  out[name] = shapes;
}

const body = Object.entries(out)
  .map(([name, shapes]) => `  ${name}: {\n${Object.entries(shapes).map(([w, s]) => `    ${w}: ${JSON.stringify(s)},`).join('\n')}\n  },`)
  .join('\n');
writeFileSync(
  new URL('../src/lib/icons.ts', import.meta.url),
  `// Generated by scripts/icons.mjs from Phosphor Icons (MIT, phosphoricons.com). Don't edit.
export type Weight = 'regular' | 'bold' | 'fill';

/** SVG shapes on a 256 by 256 grid, by icon and weight. */
export const ICONS: Record<string, Partial<Record<Weight, string>> & { regular: string }> = {
${body}
};
`,
);
console.log(`${Object.keys(out).length} icons`);
